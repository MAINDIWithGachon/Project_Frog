using UnityEngine;

/// <summary>
/// 현재 시점의 "최종 스탯 결과값"을 보관하는 런타임 데이터.
/// 
/// 이 클래스는 서버에 저장되는 원본 데이터가 아니라,
/// RuntimeData(스탯 레벨, 장비, 레시피, 버프 등)를 바탕으로
/// PlayerStatController가 계산한 최종 수치를 담아두는 용도이다.
/// 
/// 예시 흐름:
/// 1. RuntimeData에 공격력 레벨, 체력 레벨 등이 저장되어 있음
/// 2. PlayerStatController가 기본값 + 스탯 강화 + 장비 + 레시피 + 버프를 합산
/// 3. 계산 결과를 FinalStatData에 기록
/// 4. SkillManager, 체력 UI, 회복 시스템 등이 이 값을 참조
/// 
/// 즉, 이 클래스는
/// "지금 캐릭터가 실제로 가지고 있는 최종 능력치"를 들고 있는 캐시라고 보면 된다.
/// </summary>
public class FinalStatData : MonoBehaviour
{
    /// <summary>
    /// 현재 최종 공격력.
    /// 
    /// 포함 가능 항목 예시:
    /// - 기본 공격력
    /// - 스탯 강화 공격력
    /// - 장비 추가 공격력
    /// - 레시피 추가 공격력
    /// - 버프/스킬로 증가한 일시 공격력
    /// 
    /// 값 예시:
    /// - attack = 185 이면 현재 최종 공격력은 185이다.
    /// - "공격력의 200% 피해" 스킬 사용 시 185 * 2 = 370 계산의 기준이 된다.
    /// 
    /// 스킬 피해 계산 시 가장 자주 참조되는 값이다.
    /// </summary>
    public float attack;

    /// <summary>
    /// 현재 최종 최대 체력.
    /// 
    /// 포함 가능 항목 예시:
    /// - 기본 체력
    /// - 스탯 강화 체력
    /// - 장비 체력
    /// - 레시피 체력
    /// - 버프/스킬로 증가한 일시 체력
    /// 
    /// 값 예시:
    /// - maxHp = 250 이면 캐릭터의 최대 체력은 250이다.
    /// - 체력바 UI의 최대값, 회복 상한선, 생존 판정 기준으로 사용된다.
    /// 
    /// 현재 체력 UI의 최대값 기준이나 생존 계산의 기준이 된다.
    /// </summary>
    public float maxHp;

    /// <summary>
    /// 현재 최종 초당 체력 회복량.
    /// 
    /// 포함 가능 항목 예시:
    /// - 기본 초당 체력 회복
    /// - 스탯 강화 회복량
    /// - 장비 회복량
    /// - 레시피 회복량
    /// - 버프/스킬로 증가한 일시 회복량
    /// 
    /// 값 예시:
    /// - hpRegenPerSecond = 10 이면 1초마다 체력을 10 회복한다.
    /// - hpRegenPerSecond = 2.5 이면 1초마다 체력을 2.5 회복한다.
    /// 
    /// 매 초 체력 자동 회복 시스템에서 참조할 수 있다.
    /// </summary>
    public float hpRegenPerSecond;

    /// <summary>
    /// 현재 최종 치명타 확률.
    /// 
    /// 일반적으로 0~100 범위를 사용하며,
    /// 필요하다면 계산 단계에서 최대값 제한(Clamp)을 걸어주는 것이 좋다.
    /// 
    /// 포함 가능 항목 예시:
    /// - 기본 치명타 확률
    /// - 스탯 강화 치명타 확률
    /// - 장비 치명타 확률
    /// - 레시피 치명타 확률
    /// - 버프/스킬로 증가한 일시 치명타 확률
    /// 
    /// 값 예시:
    /// - critChance = 80 이면 치명타 확률 80%를 의미한다.
    /// - critChance = 25.5 이면 치명타 확률 25.5%를 의미한다.
    /// 
    /// 즉, 이 값은 내부적으로 "퍼센트 값 자체"를 들고 있다고 보면 된다.
    /// </summary>
    public float critChance;

    /// <summary>
    /// 현재 최종 치명타 공격력.
    /// 
    /// 치명타 발생 시 추가로 적용되는 피해 배율 또는 추가 피해 수치 계산에 사용된다.
    /// 프로젝트 기준에 따라 퍼센트(%) 개념으로 사용할 수도 있고,
    /// 배율 개념으로 사용할 수도 있으므로 계산 규칙은 별도로 통일해야 한다.
    /// 
    /// 포함 가능 항목 예시:
    /// - 기본 치명타 공격력
    /// - 스탯 강화 치명타 공격력
    /// - 장비 치명타 공격력
    /// - 레시피 치명타 공격력
    /// - 버프/스킬로 증가한 일시 치명타 공격력
    /// 
    /// 값 예시(퍼센트 방식으로 사용할 경우):
    /// - critDamage = 50 이면 치명타 피해 +50%를 의미한다.
    /// - critDamage = 150 이면 치명타 피해 +150%를 의미한다.
    /// 
    /// 예를 들어 "기본 100% + 추가 치명타 공격력 50%" 구조라면
    /// critDamage = 50 일 때 치명타 시 총 150% 피해로 계산할 수 있다.
    /// 
    /// ※ 이 값은 프로젝트 전체에서
    /// "추가 퍼센트"로 볼지, "최종 퍼센트"로 볼지 반드시 통일해야 한다.
    /// </summary>
    public float critDamage;
}